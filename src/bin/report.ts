// npm run report -- --version v1
//
// Regenerates results/<version>/results.csv and results/<version>/LEADERBOARD.md
// from every run directory, then injects the leaderboard into README.md between
// the marker comments. Nothing in either file is written by hand.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../corpus.js";
import { injectLeaderboard, renderLeaderboard } from "../report/leaderboard.js";
import { loadRuns, resultsDir } from "../report/load.js";
import { toCsv } from "../report/rows.js";

function arg(name: string, fallback: string): string {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? fallback : (process.argv[index + 1] ?? fallback);
}

const version = arg("version", "v1");
const bundles = loadRuns(version);
const dir = resultsDir(version);
mkdirSync(dir, { recursive: true });

writeFileSync(join(dir, "results.csv"), toCsv(bundles));

const block = renderLeaderboard(bundles);
writeFileSync(
  join(dir, "LEADERBOARD.md"),
  `# Leaderboard, corpus ${version}\n\nGenerated by \`npm run report\`. Do not edit by hand.\n\n${block}\n`,
);

const readmePath = join(REPO_ROOT, "README.md");
if (existsSync(readmePath)) {
  writeFileSync(readmePath, injectLeaderboard(readFileSync(readmePath, "utf8"), block));
}

console.log(`report for ${version}: ${bundles.length} runs, ${bundles.reduce((total, b) => total + b.items.length, 0)} rows`);
